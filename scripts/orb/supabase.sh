#!/usr/bin/env bash
# Amp orb service (see .amp/services.yaml): runs the local Supabase stack in
# Docker, points the dev server at it and seeds the demo family once.
# WEB_URL is the web service's portal URL, supplied by Amp.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/../.."
: "${WEB_URL:?WEB_URL must be the web service portal URL}"

# The docker service starts alongside this one; wait for its daemon.
until docker info >/dev/null 2>&1; do sleep 1; done

# Edge Function secrets. `supabase start` copies supabase/functions/.env
# (git-ignored) into the functions container. Local-only values are generated
# once per orb; keys only the developer has are taken from the orb
# environment (Amp project secrets) when set.
functions_env=supabase/functions/.env
touch "$functions_env"
env_get() { sed -n "s/^$1=//p" "$functions_env"; }
env_set() {
	local others
	others="$(grep -v "^$1=" "$functions_env" || true)"
	printf '%s\n%s=%s\n' "$others" "$1" "$2" | sed '/^$/d' >"$functions_env"
}
for name in CRON_SECRET GCAL_STATE_SECRET; do
	if [[ -z "$(env_get "$name")" ]]; then env_set "$name" "$(openssl rand -hex 32)"; fi
done
# Without VAPID keys the push functions crash on load. A generated pair lets
# them run; delivery to a real device needs the production pair, whose public
# half is committed in src/lib/pwa-config.ts.
if [[ -z "$(env_get VAPID_PRIVATE_KEY)" ]]; then
	{ read -r vapid_public; read -r vapid_private; } < <(node -e '
		const { publicKey, privateKey } = require("crypto").generateKeyPairSync("ec", { namedCurve: "prime256v1" });
		const pub = publicKey.export({ format: "jwk" });
		const raw = Buffer.concat([Buffer.from([4]), Buffer.from(pub.x, "base64url"), Buffer.from(pub.y, "base64url")]);
		console.log(raw.toString("base64url"));
		console.log(privateKey.export({ format: "jwk" }).d);')
	env_set VAPID_PUBLIC_KEY "$vapid_public"
	env_set VAPID_PRIVATE_KEY "$vapid_private"
fi
if [[ -z "$(env_get VAPID_SUBJECT)" ]]; then env_set VAPID_SUBJECT mailto:dev@porodica.test; fi
for name in VAPID_PUBLIC_KEY VAPID_PRIVATE_KEY VAPID_SUBJECT TYPESAFE_API_KEY GOOGLE_CLIENT_ID GOOGLE_CLIENT_SECRET; do
	if [[ -n "${!name:-}" ]]; then env_set "$name" "${!name}"; fi
done
# Google Calendar returns through the portal; Google must allow this redirect URI.
env_set APP_URL "${WEB_URL%/}"
env_set GCAL_REDIRECT_URI "${WEB_URL%/}/supabase/functions/v1/gcal-oauth-callback"

# A running stack keeps the secrets it started with: restart it (data stays)
# when they changed since the last start.
applied_hash_file=supabase/.temp/orb-functions-env.sha256
functions_env_hash="$(sha256sum "$functions_env" | cut -d' ' -f1)"
if [[ "$(cat "$applied_hash_file" 2>/dev/null || true)" != "$functions_env_hash" ]]; then
	supabase stop
fi

# Idempotent: applies migrations on a fresh database, no-op when running.
# After a Docker restart the containers come back on their own and `start`
# fails until Postgres is healthy again, so retry for a minute.
for _ in {1..30}; do supabase start && break || sleep 2; done
eval "$(supabase status -o env)"
mkdir -p "$(dirname "$applied_hash_file")"
printf '%s\n' "$functions_env_hash" >"$applied_hash_file"

# Database side of the functions. Triggers and pg_cron send X-Cron-Secret
# from the vault entry cron_secret, so it must match the functions' secret.
# The gcal-sync job from the migrations calls the production URL; point this
# database's copy at its own functions instead.
project_id="$(sed -nE 's/^project_id = "(.*)"/\1/p' supabase/config.toml)"
docker exec -i "supabase_db_$project_id" psql -U postgres -d postgres -v ON_ERROR_STOP=1 -q \
	-v cron_secret="$(env_get CRON_SECRET)" >/dev/null <<'SQL'
SELECT CASE
  WHEN EXISTS (SELECT 1 FROM vault.secrets WHERE name = 'cron_secret')
  THEN (SELECT vault.update_secret(id, :'cron_secret') FROM vault.secrets WHERE name = 'cron_secret')::text
  ELSE vault.create_secret(:'cron_secret', 'cron_secret', 'Local orb secret for pg_cron and triggers')::text
END;
SELECT cron.alter_job(jobid, command := replace(command,
  '''https://tiokicffpbzqgrsqrkgt.supabase.co/functions/v1/gcal-sync''',
  'edge_functions_base_url() || ''/gcal-sync'''))
FROM cron.job WHERE jobname = 'gcal-sync-every-15-min' AND command LIKE '%supabase.co%';
SQL

# The browser reaches Supabase through the dev server's /supabase proxy
# (vite.config.ts). Vite restarts itself when this file changes, so only
# rewrite it when the content differs.
env_file=.env.development.local
env_content="# Generated by scripts/orb/supabase.sh - local Supabase in this orb.
VITE_SUPABASE_URL=${WEB_URL%/}/supabase
VITE_SUPABASE_ANON_KEY=$ANON_KEY"
if [[ "$(cat "$env_file" 2>/dev/null || true)" != "$env_content" ]]; then
	printf '%s\n' "$env_content" >"$env_file"
fi

# Seed each database once. seed-demo.ts recreates its family on every run, so
# rerunning it would wipe what was changed during the orb's lifetime. The
# "seeded" marker is a database setting written only after the seed succeeds:
# it lives in the same Docker volume as the data (a reset or new orb clears
# it), and an interrupted or failed seed is retried on the next start -
# seed-demo.ts first deletes the half-built demo family.
db_psql() { docker exec "supabase_db_$project_id" psql -U supabase_admin -d postgres -v ON_ERROR_STOP=1 -tAc "$1"; }
# A plain assignment, so a failed query stops the script (set -e) instead of
# reading as "not seeded" and wiping the demo family.
seeded="$(db_psql "select current_setting('orb.demo_seeded', true)")"
if [[ "$seeded" != done ]]; then
	SUPABASE_URL="$API_URL" SUPABASE_SERVICE_ROLE_KEY="$SERVICE_ROLE_KEY" \
		pnpm exec tsx scripts/seed-demo.ts
	db_psql "alter database postgres set orb.demo_seeded = 'done'" >/dev/null
else
	echo "The demo family was already seeded in this database; skipping."
fi

# The containers belong to dockerd; this process only keeps the service up.
exec sleep infinity
